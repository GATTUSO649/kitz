ALTER TABLE "admin_users"
  ADD COLUMN IF NOT EXISTS "role_number" varchar(40) UNIQUE,
  ADD COLUMN IF NOT EXISTS "role" varchar(32),
  ADD COLUMN IF NOT EXISTS "status" varchar(24) NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS "suspended_at" timestamptz,
  ADD COLUMN IF NOT EXISTS "suspended_reason" text,
  ADD COLUMN IF NOT EXISTS "last_login_at" timestamptz,
  ADD COLUMN IF NOT EXISTS "password_updated_at" timestamptz;

UPDATE "admin_users"
SET "role" = CASE
  WHEN EXISTS (
    SELECT 1 FROM "operations_operators" operators
    WHERE operators."admin_user_id" = "admin_users"."id"
      AND operators."it_role" = 'super_admin'
      AND operators."revoked_at" IS NULL
  ) THEN 'super_admin'
  WHEN EXISTS (
    SELECT 1 FROM "operations_operators" operators
    WHERE operators."admin_user_id" = "admin_users"."id"
      AND operators."revoked_at" IS NULL
  ) THEN 'it_admin'
  ELSE 'sales_admin'
END
WHERE "role" IS NULL;

WITH ranked AS (
  SELECT "id",
    CASE "role"
      WHEN 'super_admin' THEN 'SUPER'
      WHEN 'it_admin' THEN 'IT'
      WHEN 'sales_admin' THEN 'SALES'
      WHEN 'finance_admin' THEN 'FIN'
      WHEN 'inventory_admin' THEN 'INV'
      WHEN 'marketing_admin' THEN 'MKT'
      WHEN 'content_admin' THEN 'CONTENT'
    END AS prefix,
    ROW_NUMBER() OVER (PARTITION BY "role" ORDER BY "id") AS sequence
  FROM "admin_users"
  WHERE "role_number" IS NULL
)
UPDATE "admin_users" AS admins
SET "role_number" = ranked.prefix || '-' || LPAD(ranked.sequence::text, 4, '0')
FROM ranked
WHERE admins."id" = ranked.id;

UPDATE "admin_users"
SET "status" = CASE WHEN "email_verified_at" IS NULL THEN 'pending' WHEN "suspended_at" IS NOT NULL THEN 'suspended' ELSE 'active' END;

DO $$ BEGIN
  ALTER TABLE "admin_users" ADD CONSTRAINT "admin_users_role_check"
    CHECK ("role" IS NULL OR "role" IN ('super_admin', 'it_admin', 'sales_admin', 'finance_admin', 'inventory_admin', 'marketing_admin', 'content_admin'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  ALTER TABLE "admin_users" ADD CONSTRAINT "admin_users_status_check"
    CHECK ("status" IN ('pending', 'active', 'suspended', 'disabled'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
CREATE INDEX IF NOT EXISTS "admin_users_role_idx" ON "admin_users" ("role");
CREATE INDEX IF NOT EXISTS "admin_users_status_idx" ON "admin_users" ("status");

CREATE TABLE IF NOT EXISTS "admin_permissions" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "permission" varchar(120) NOT NULL UNIQUE,
  "description" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "admin_role_permissions" (
  "role" varchar(32) NOT NULL,
  "permission" varchar(120) NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("role", "permission")
);

CREATE TABLE IF NOT EXISTS "admin_user_permissions" (
  "admin_user_id" integer NOT NULL REFERENCES "admin_users"("id") ON DELETE CASCADE,
  "permission" varchar(120) NOT NULL,
  "granted" boolean NOT NULL,
  "granted_by_admin_user_id" integer REFERENCES "admin_users"("id") ON DELETE SET NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "revoked_at" timestamptz,
  PRIMARY KEY ("admin_user_id", "permission")
);

CREATE TABLE IF NOT EXISTS "admin_invitations" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "invitation_id" varchar(36) NOT NULL UNIQUE,
  "admin_user_id" integer NOT NULL REFERENCES "admin_users"("id") ON DELETE CASCADE,
  "email" varchar(254) NOT NULL,
  "role" varchar(32) NOT NULL,
  "token_hash" varchar(64) NOT NULL UNIQUE,
  "password_hash" varchar(255),
  "expires_at" timestamptz NOT NULL,
  "consumed_at" timestamptz,
  "delivered_at" timestamptz,
  "delivery_status" varchar(24) NOT NULL DEFAULT 'queued',
  "delivery_error_code" varchar(80),
  "created_at" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "admin_invitations_admin_idx" ON "admin_invitations" ("admin_user_id");
CREATE INDEX IF NOT EXISTS "admin_invitations_email_idx" ON "admin_invitations" ("email");
CREATE INDEX IF NOT EXISTS "admin_invitations_status_idx" ON "admin_invitations" ("delivery_status", "expires_at");

CREATE TABLE IF NOT EXISTS "admin_login_attempts" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "identity" varchar(254) NOT NULL,
  "admin_user_id" integer REFERENCES "admin_users"("id") ON DELETE SET NULL,
  "success" boolean NOT NULL DEFAULT false,
  "failure_code" varchar(80),
  "request_id" varchar(120),
  "ip_hash" varchar(64),
  "created_at" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "admin_login_attempts_identity_idx" ON "admin_login_attempts" ("identity", "created_at");
