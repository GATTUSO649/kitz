function normalizeTeamName(name: string) {
  return name.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
}

export function matchesNationalTeam(selectedName: string, productTeamName: string | null | undefined) {
  if (!productTeamName) return false
  const productName = normalizeTeamName(productTeamName)
  return [selectedName, ...(NATIONAL_TEAM_ALIASES[selectedName] ?? [])]
    .some((name) => normalizeTeamName(name) === productName)
}